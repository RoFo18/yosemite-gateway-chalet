#!/usr/bin/env python3
"""Write the domain-level 301s at the top of public/_redirects.

Every alias domain forwards to the primary domain in one hop. Old WordPress paths on
yosemitegatewaychalet.com go straight to their new pages on the primary, so search engines
never follow a chain. Run after changing ALIASES or the legacy path rules, then commit.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "public", "_redirects")
PRIMARY = "https://yosemitechalet.us"
ALIASES = ["yosemitegatewaychalet.com", "capitopia.com", "impactwheelhouse.com", "skijunemountain.com"]
LEGACY_HOST = "yosemitegatewaychalet.com"   # the old WordPress site; its old paths map to new pages
START, END = "# >>> domain redirects (generated by scripts/domain_redirects.py)", "# <<< domain redirects"

text = open(PATH).read()
if START in text:
    text = text[:text.index(START)] + text[text.index(END) + len(END):].lstrip("\n")

legacy = []
for line in text.splitlines():
    parts = line.split()
    if len(parts) == 3 and parts[0].startswith("/") and parts[2] == "301":
        legacy.append((parts[0], parts[1]))

out = [START, "# One canonical home: " + PRIMARY, ""]
out.append(f"https://www.yosemitechalet.us/*    {PRIMARY}/:splat    301!")
for host in [LEGACY_HOST, "www." + LEGACY_HOST]:
    for src, dst in legacy:
        out.append(f"https://{host}{src}    {PRIMARY}{dst}    301!")
for alias in ALIASES:
    for host in (alias, "www." + alias):
        out.append(f"https://{host}/*    {PRIMARY}/:splat    301!")
out += [END, ""]
open(PATH, "w").write("\n".join(out) + "\n" + text)
print(f"{len(out) - 5} domain rules written")
